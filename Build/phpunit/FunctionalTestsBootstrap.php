/**
 * Functional test phpunit bootstrap, defined in FunctionalTests.xml and called by
 * phpunit before the test suites are instantiated.
 *
 * Copied from typo3/testing-framework's boilerplate
 * (Resources/Core/Build/FunctionalTestsBootstrap.php), whose header asks extensions
 * to copy it rather than reference it.
 *
 * Run the suite through `Build/Scripts/runTests.sh -s functional`.
 */

use SBUERK\AvailableFixturePackages;
use TYPO3\TestingFramework\Core\Testbase;

(static function (): void {
    $testbase = new Testbase();
    $testbase->defineOriginalRootPath();
    $testbase->createDirectory(ORIGINAL_ROOT . 'typo3temp/var/tests');
    $testbase->createDirectory(ORIGINAL_ROOT . 'typo3temp/var/transient');

    // Registers the fixture extensions under Tests/Fixtures/Extensions/ with the
    // testing framework's ComposerPackageManager, so $testExtensionsToLoad can name
    // them by extension key or composer package name. Generated by the composer
    // plugin sbuerk/fixture-packages, which only runs in dev mode.
    if (class_exists(AvailableFixturePackages::class)) {
        (new AvailableFixturePackages())->adoptFixtureExtensions();
    }
})();
